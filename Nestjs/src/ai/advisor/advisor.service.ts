import { Injectable } from '@nestjs/common';
import { PerformanceService } from '../../analytics/performance.service';
import { RiskService } from '../../analytics/risk.service';
import { RISK_DISCLAIMER } from '../../analytics/risk';
import { AssignmentsService } from '../../assignments/assignments.service';
import { AttendanceAnalyticsService } from '../../attendance/attendance-analytics.service';
import { PaginationQueryDto } from '../../common/dto/pagination.dto';
import { Principal } from '../../common/types/principal';
import { ExaminationsService } from '../../examinations/examinations.service';
import { AiClient } from '../ai-client.service';
import { StudentResolver } from '../tools/student-resolver';
import { Recommendation, buildStudyPlan } from './study-plan';

@Injectable()
export class AdvisorService {
  constructor(
    private readonly perf: PerformanceService,
    private readonly risk: RiskService,
    private readonly attendance: AttendanceAnalyticsService,
    private readonly exams: ExaminationsService,
    private readonly assignments: AssignmentsService,
    private readonly ai: AiClient,
    private readonly resolver: StudentResolver,
  ) {}

  /** Personal academic advisor. `collegeData` = facts from records; `recommendations` = generated suggestions. */
  async advise(p: Principal, collegeId: string, studentId?: string, narrate = true) {
    const id = await this.resolver.resolve({ principal: p, collegeId }, studentId);
    const q = Object.assign(new PaginationQueryDto(), { page: 1, limit: 50, pending: 'true' });
    const [performance, attendance, exams, pending, risk] = await Promise.all([
      this.perf.forStudent(collegeId, id),
      this.attendance.report(collegeId, id),
      this.exams.upcomingForStudent(collegeId, id, 30),
      this.assignments.listForStudent(collegeId, id, q),
      this.risk.assess(collegeId, id, false),
    ]);
    const day = 86_400_000;
    const examFacts = exams.map((e) => ({
      subject: e.subjectOffering.subject.name,
      subjectId: e.subjectOffering.subject.id,
      daysAway: Math.ceil((e.scheduledAt.getTime() - Date.now()) / day),
      date: e.scheduledAt.toISOString(),
    }));
    const pendingFacts = pending.data.map((a) => ({
      title: a.title,
      subject: a.subjectOffering.subject.name,
      dueInDays: Math.ceil((a.dueAt.getTime() - Date.now()) / day),
    }));

    const recommendations: Recommendation[] = buildStudyPlan({
      exams: examFacts,
      overallExamAvg: performance.examAvgPct,
      attendanceFlags: attendance.flags,
      pendingAssignments: pendingFacts,
      subjects: performance.subjects.map((s) => ({
        subjectId: s.subjectId,
        name: s.name,
        examAvgPct: s.examAvgPct,
        weak: s.weak,
        weakReasons: s.weakReasons,
        attendancePct: s.attendancePct,
      })),
    });

    let narrative: string | undefined;
    if (narrate && this.ai.isConfigured() && recommendations.length) {
      try {
        const res = await this.ai.chat(
          { collegeId, userId: p.userId },
          {
            temperature: 0.4,
            maxTokens: 350,
            messages: [
              {
                role: 'system',
                content:
                  'You are a supportive academic advisor. Write a short, encouraging study plan (max 6 lines) using ONLY the facts and recommendations in the JSON. Do not mention units, chapters or topics, marks, dates or numbers that are not in the JSON. Do not guarantee outcomes.',
              },
              {
                role: 'user',
                content: JSON.stringify({ recommendations: recommendations.slice(0, 6), riskLevel: risk.level }),
              },
            ],
          },
        );
        narrative = res.content?.trim() || undefined;
      } catch {
        /* the rule-based plan is still returned */
      }
    }

    return {
      collegeData: {
        // verified records
        upcomingExams: examFacts,
        pendingAssignments: pendingFacts,
        overallExamAverage: performance.examAvgPct,
        cgpa: performance.cgpa,
        weakSubjects: performance.subjects
          .filter((s) => s.weak)
          .map((s) => ({ subject: s.name, reasons: s.weakReasons })),
        attendance: { overall: attendance.overall.percentage, minimum: attendance.threshold, flags: attendance.flags },
      },
      recommendations, // generated by rules from the records above
      riskIndicator: { level: risk.level, reasons: risk.reasons, confidence: risk.confidence },
      narrative, // optional LLM wording of the same recommendations
      generatedBy: narrative ? 'rules+llm' : 'rules',
      disclaimer: `Recommendations are AI/rule-generated suggestions, not official college guidance. ${RISK_DISCLAIMER}`,
    };
  }
}
